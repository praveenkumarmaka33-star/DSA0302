from transformers import AutoTokenizer, AutoModelForSeq2SeqLM

# Load the specific tokenizer and model for translation
model_name = "Helsinki-NLP/opus-mt-en-fr"
tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForSeq2SeqLM.from_pretrained(model_name)

# Get input
text = input("Enter English sentence: ")

# Tokenize, generate translation, and decode
inputs = tokenizer(text, return_tensors="pt")
translation_ids = model.generate(**inputs)
result = tokenizer.decode(translation_ids[0], skip_special_tokens=True)

# Display output
print("French Translation:", result)